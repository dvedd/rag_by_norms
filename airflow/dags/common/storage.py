import logging
from pathlib import Path
from tempfile import TemporaryDirectory
from typing import TYPE_CHECKING

from botocore.exceptions import BotoCoreError, ClientError
from common.logging import log_failure

if TYPE_CHECKING:
    from airflow.providers.amazon.aws.hooks.s3 import S3Hook

logger = logging.getLogger(__name__)


def del_file(file: str | Path) -> None:
    """Remove a local file if it exists."""
    path = Path(file)
    if path.exists():
        path.unlink()
        logger.debug("Removed local file")


def load_to_s3(
    hook: "S3Hook",
    filepath: str | list[str],
    bucket_name: str = "ragfiles",
    prefix: str = "dev_data/mineru_md",
) -> list[str] | None:
    """Upload files in order and return their keys, or None on storage failure."""
    paths = filepath if isinstance(filepath, list) else [filepath]
    keys: list[str] = []

    try:
        for path in paths:
            key = f"{prefix}/{Path(path).name}"
            hook.load_file(filename=path, bucket_name=bucket_name, key=key, replace=True)
            keys.append(key)
    except (BotoCoreError, ClientError, OSError) as error:
        log_failure(logger=logger, operation="Upload document files", error=error)

        return None

    logger.info("Uploaded %s document files", len(keys))

    return keys


def read_s3_text(
    hook: "S3Hook",
    key: str,
    bucket_name: str = "ragfiles",
) -> str | None:
    """Download text into an isolated directory and remove it after reading."""
    with TemporaryDirectory(prefix="rag-markdown-") as directory:
        try:
            file_path = hook.download_file(
                key=key,
                bucket_name=bucket_name,
                local_path=directory,
                preserve_file_name=True,
                use_autogenerated_subdir=False,
            )
        except (BotoCoreError, ClientError, OSError) as error:
            log_failure(logger=logger, operation="Download source markdown", error=error)

            return None

        return Path(file_path).read_text(encoding="utf-8")
